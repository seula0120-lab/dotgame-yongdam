// 글자 글리프 (7장). 한글은 12x12, 영문은 6x12, 글자색 7, 나머지는 투명(-1).
// 획 목록을 격자에 찍어 팔레트 인덱스 배열로 만든다. fillText는 쓰지 않는다.
const H = (x1, x2, y) => Array.from({ length: x2 - x1 + 1 }, (_, i) => [x1 + i, y]);
const V = (x, y1, y2) => Array.from({ length: y2 - y1 + 1 }, (_, i) => [x, y1 + i]);
const O = (x, y, w, h) => [...H(x + 1, x + w - 2, y), ...H(x + 1, x + w - 2, y + h - 1), ...V(x, y + 1, y + h - 2), ...V(x + w - 1, y + 1, y + h - 2)];
const P = (...pts) => pts;
const SI = (x, y) => P([x + 2, y], [x + 1, y + 1], [x + 1, y + 2], [x, y + 3], [x + 3, y + 1], [x + 3, y + 2], [x + 4, y + 3]);
function strokes(list, w = 12) {
  const g = Array.from({ length: 12 }, () => Array(w).fill(-1));
  for (const [x, y] of list.flat()) if (x >= 0 && x < w && y >= 0 && y < 12) g[y][x] = 7;
  return g;
}
