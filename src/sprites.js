// 숫자 글리프 0~9, 6x12 픽셀, 글자색 7 (R2). 3x5 도트를 2배로 키우고 위아래 1줄 비운다.
const DIGIT_3X5 = [
  ["111", "101", "101", "101", "111"],
  ["010", "110", "010", "010", "111"],
  ["111", "001", "111", "100", "111"],
  ["111", "001", "111", "001", "111"],
  ["101", "101", "111", "001", "001"],
  ["111", "100", "111", "001", "111"],
  ["111", "100", "111", "101", "111"],
  ["111", "001", "001", "001", "001"],
  ["111", "101", "111", "101", "111"],
  ["111", "101", "111", "001", "111"],
];
export const GLYPH_W = 6;
export const GLYPH_H = 12;
export const DIGITS = DIGIT_3X5.map((rows) => {
  const out = [Array(GLYPH_W).fill(-1)];
  for (const row of rows) {
    const line = [...row].flatMap((c) => (c === "1" ? [7, 7] : [-1, -1]));
    out.push(line, [...line]);
  }
  out.push(Array(GLYPH_W).fill(-1));
  return out;
});
