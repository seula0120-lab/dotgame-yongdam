// 스프라이트는 팔레트 인덱스 배열. -1은 투명.
// 한 글자가 한 픽셀: 0~7은 팔레트 인덱스, '.'은 투명.
function sprite(rows) {
  return rows.map((row) => [...row].map((c) => (c === "." ? -1 : Number(c))));
}

